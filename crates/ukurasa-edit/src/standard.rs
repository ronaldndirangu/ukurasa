//! The standard PDF fonts Ukurasa draws with, in WinAnsiEncoding. Widths come from Adobe's Core 14
//! AFM files.

use lopdf::{Dictionary, Object, dictionary};
use serde::{Deserialize, Serialize};

/// A generic font family, for choosing a standard font or a stand-in font while editing.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum Family {
    Serif,
    Sans,
    Mono,
}

/// One of the standard Helvetica, Times, and Courier faces every PDF viewer has.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct Standard {
    pub family: Family,
    pub bold: bool,
    pub italic: bool,
}

impl Standard {
    #[cfg(test)]
    pub const HELVETICA: Standard = Standard {
        family: Family::Sans,
        bold: false,
        italic: false,
    };

    /// The standard family named `name`, as Ukurasa lists it.
    pub fn named(name: &str) -> Option<Family> {
        match name {
            "Helvetica" => Some(Family::Sans),
            "Times" => Some(Family::Serif),
            "Courier" => Some(Family::Mono),
            _ => None,
        }
    }

    pub fn family_name(self) -> &'static str {
        match self.family {
            Family::Sans => "Helvetica",
            Family::Serif => "Times",
            Family::Mono => "Courier",
        }
    }

    pub fn base_font(self) -> &'static str {
        match (self.family, self.bold, self.italic) {
            (Family::Sans, false, false) => "Helvetica",
            (Family::Sans, true, false) => "Helvetica-Bold",
            (Family::Sans, false, true) => "Helvetica-Oblique",
            (Family::Sans, true, true) => "Helvetica-BoldOblique",
            (Family::Serif, false, false) => "Times-Roman",
            (Family::Serif, true, false) => "Times-Bold",
            (Family::Serif, false, true) => "Times-Italic",
            (Family::Serif, true, true) => "Times-BoldItalic",
            (Family::Mono, false, false) => "Courier",
            (Family::Mono, true, false) => "Courier-Bold",
            (Family::Mono, false, true) => "Courier-Oblique",
            (Family::Mono, true, true) => "Courier-BoldOblique",
        }
    }

    /// Width of one WinAnsi code in thousandths of an em; zero when the code has no glyph.
    pub fn code_width(self, code: u8) -> f64 {
        let table = match (self.family, self.bold, self.italic) {
            (Family::Sans, false, _) => &HELVETICA,
            (Family::Sans, true, _) => &HELVETICA_BOLD,
            (Family::Serif, false, false) => &TIMES_ROMAN,
            (Family::Serif, true, false) => &TIMES_BOLD,
            (Family::Serif, false, true) => &TIMES_ITALIC,
            (Family::Serif, true, true) => &TIMES_BOLDITALIC,
            (Family::Mono, ..) => {
                return if HELVETICA[code as usize] == 0 {
                    0.0
                } else {
                    600.0
                };
            }
        };
        f64::from(table[code as usize])
    }

    /// Width of WinAnsi-encoded text in thousandths of an em.
    #[cfg(test)]
    pub fn width(self, encoded: &[u8]) -> f64 {
        encoded.iter().map(|&b| self.code_width(b)).sum()
    }

    /// The font dictionary, with explicit widths so viewers place glyphs where they were
    /// measured whatever font they substitute.
    pub fn dictionary(self) -> Dictionary {
        dictionary! {
            "Type" => "Font",
            "Subtype" => "Type1",
            "BaseFont" => self.base_font(),
            "Encoding" => "WinAnsiEncoding",
            "FirstChar" => 32,
            "LastChar" => 255,
            "Widths" => (32..=255u8)
                .map(|code| Object::Integer(self.code_width(code) as i64))
                .collect::<Vec<_>>(),
        }
    }
}

/// The WinAnsi code for `c`, if the encoding has one.
pub fn encode(c: char) -> Option<u8> {
    let code = match c {
        ' '..='~' | '\u{a0}'..='\u{ff}' => c as u32 as u8,
        '\u{20ac}' => 0x80,
        '\u{201a}' => 0x82,
        '\u{0192}' => 0x83,
        '\u{201e}' => 0x84,
        '\u{2026}' => 0x85,
        '\u{2020}' => 0x86,
        '\u{2021}' => 0x87,
        '\u{02c6}' => 0x88,
        '\u{2030}' => 0x89,
        '\u{0160}' => 0x8a,
        '\u{2039}' => 0x8b,
        '\u{0152}' => 0x8c,
        '\u{017d}' => 0x8e,
        '\u{2018}' => 0x91,
        '\u{2019}' => 0x92,
        '\u{201c}' => 0x93,
        '\u{201d}' => 0x94,
        '\u{2022}' => 0x95,
        '\u{2013}' => 0x96,
        '\u{2014}' => 0x97,
        '\u{02dc}' => 0x98,
        '\u{2122}' => 0x99,
        '\u{0161}' => 0x9a,
        '\u{203a}' => 0x9b,
        '\u{0153}' => 0x9c,
        '\u{017e}' => 0x9e,
        '\u{0178}' => 0x9f,
        _ => return None,
    };
    Some(code)
}
