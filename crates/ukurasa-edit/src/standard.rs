#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn encodes_ascii_latin1_and_windows_extras() {
        assert_eq!(encode('A'), Some(0x41));
        assert_eq!(encode('\u{e9}'), Some(0xe9));
        assert_eq!(encode('\u{20ac}'), Some(0x80));
        assert_eq!(encode('\u{4e2d}'), None);
        assert_eq!(encode('\n'), None);
    }

    #[test]
    fn measures_known_widths() {
        let helvetica = Standard::HELVETICA;
        assert_eq!(
            helvetica.width(b"Hello"),
            722.0 + 556.0 + 222.0 + 222.0 + 556.0
        );
        assert_eq!(helvetica.width(b" "), 278.0);
        let times_bold = Standard {
            family: Family::Serif,
            bold: true,
            italic: false,
        };
        assert_eq!(times_bold.width(b"W"), 1000.0);
        assert_eq!(times_bold.base_font(), "Times-Bold");
        let courier = Standard {
            family: Family::Mono,
            bold: true,
            italic: true,
        };
        assert_eq!(
            (courier.width(b"iW"), courier.code_width(0x81)),
            (1200.0, 0.0)
        );
    }
}
